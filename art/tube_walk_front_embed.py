"""Embeds tube_walk_data/front.png (our own 1-bit annotation mask: what
stands in front of the walkable glass tube) in the engine's source, as
src/openc2e/madeart/tube_walk_front_data.inc, for the C++ port's load_front
(tube_walk_parts.cpp): the engine can't rely on the art folder at run time.

The mask, as tube_walk.py's load_front reads it (convert('1'), C order),
is stored as run lengths: alternating runs of clear and set pixels, the
first clear (it may be 0 long).

    python3 art/tube_walk_front_embed.py           write the .inc
    python3 art/tube_walk_front_embed.py --check   prove the .inc equals the PNG
"""
import os
import re
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PNG = os.path.join(HERE, 'tube_walk_data', 'front.png')
INC = os.path.join(HERE, '..', 'src', 'openc2e', 'madeart', 'tube_walk_front_data.inc')


def mask():
    return np.asarray(Image.open(PNG).convert('1'))


def runs(m):
    flat = m.ravel()
    edges = np.nonzero(flat[1:] != flat[:-1])[0] + 1
    bounds = np.concatenate([[0], edges, [flat.size]])
    r = list(np.diff(bounds))
    if flat[0]:
        r = [0] + r
    return [int(v) for v in r]


def write():
    m = mask()
    r = runs(m)
    lines = []
    for i in range(0, len(r), 20):
        lines.append('\t' + ', '.join(str(v) for v in r[i:i + 20]) + ',')
    with open(INC, 'w') as f:
        f.write('// Generated by art/tube_walk_front_embed.py from art/tube_walk_data/front.png\n'
                '// (our own annotation mask, not game pixels); do not edit by hand.\n'
                '// Run lengths, C order, alternately clear and set, the first clear.\n')
        f.write('static const int kFrontW = %d, kFrontH = %d, kFrontSet = %d;\n' % (m.shape[1], m.shape[0], int(m.sum())))
        f.write('static const uint32_t kFrontRuns[] = {\n%s\n};\n' % '\n'.join(lines))
    print('wrote', os.path.normpath(INC), '(%d runs, %dx%d, %d set)' % (len(r), m.shape[1], m.shape[0], int(m.sum())))


def check():
    txt = open(INC).read()
    w, h, s = (int(re.search(r'%s = (\d+)' % k, txt).group(1)) for k in ('kFrontW', 'kFrontH', 'kFrontSet'))
    body = txt[txt.index('kFrontRuns[] = {') + len('kFrontRuns[] = {'):txt.rindex('}')]
    r = [int(v) for v in re.findall(r'\d+', body)]
    flat = np.zeros(w * h, bool)
    pos, val = 0, False
    for n in r:
        flat[pos:pos + n] = val
        pos += n
        val = not val
    m = mask()
    ok = pos == w * h and m.shape == (h, w) and int(flat.sum()) == s and np.array_equal(flat.reshape(h, w), m)
    print('embedded front mask %s the PNG (%dx%d, %d set)' % ('EQUALS' if ok else 'DIFFERS FROM', w, h, s))
    return ok


if __name__ == '__main__':
    if '--check' in sys.argv[1:]:
        sys.exit(0 if check() else 1)
    write()
