#!/usr/bin/env python3
"""Writes a C++ source file that holds the given files as byte arrays, for
openc2e's own art (data/), looked up by file name with EmbeddedFile(), and
their names with EmbeddedFileNames().

    embed_files.py OUTPUT.cpp [--func NAME] FILE...

--func names the lookup function (default EmbeddedFile; the names
function is NAME + "Names"), so several sets can be built in: the world
additions use EmbeddedAddition (Additions.h).
"""
import os
import sys


def main():
    out, files = sys.argv[1], sys.argv[2:]
    func = "EmbeddedFile"
    if files[:1] == ["--func"]:
        func, files = files[1], files[2:]
    parts = [
        "// generated by scripts/embed_files.py: do not edit\n",
        '#include <cstdint>\n#include <cstring>\n#include <span>\n#include <string>\n#include <vector>\n\n',
        "namespace {\n",
    ]
    names = []
    for i, path in enumerate(files):
        data = open(path, "rb").read()
        names.append((os.path.basename(path), i, len(data)))
        parts.append(f"const unsigned char file{i}[] = {{\n")
        for j in range(0, len(data), 24):
            parts.append(",".join(str(b) for b in data[j:j + 24]) + ",\n")
        parts.append("0};\n")
    parts.append("struct Entry {\n\tconst char* name;\n\tconst unsigned char* data;\n\tsize_t size;\n};\n")
    parts.append("const Entry entries[] = {\n")
    for name, i, size in names:
        parts.append(f'\t{{"{name}", file{i}, {size}}},\n')
    parts.append("};\n} // namespace\n\n")
    parts.append(
        f"std::span<const uint8_t> {func}(const std::string& name) {{\n"
        "\tfor (const Entry& e : entries)\n"
        "\t\tif (name == e.name)\n"
        "\t\t\treturn {e.data, e.size};\n"
        "\treturn {};\n"
        "}\n\n"
        f"std::vector<std::string> {func}Names() {{\n"
        "\tstd::vector<std::string> names;\n"
        "\tfor (const Entry& e : entries)\n"
        "\t\tnames.push_back(e.name);\n"
        "\treturn names;\n"
        "}\n"
    )
    text = "".join(parts)
    # leave the file alone when nothing changed, so it isn't rebuilt
    if os.path.exists(out) and open(out).read() == text:
        return
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
